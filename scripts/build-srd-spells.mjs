// Builds src/data/srdSpells.ts from the 5e-bits SRD 5.2 spell file (cantrips to level 3).
//
// Usage: node scripts/build-srd-spells.mjs <path to 5e-SRD-Spells.json>
// Source file: https://github.com/5e-bits/5e-database/blob/main/src/2024/en/5e-SRD-Spells.json
//
// The output is committed, so this only needs to run again to pick up a newer SRD file.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const MAX_LEVEL = 3
const input = process.argv[2]
if (!input) {
  console.error('Usage: node scripts/build-srd-spells.mjs <path to 5e-SRD-Spells.json>')
  process.exit(1)
}

const ABILITY = { Strength: 'STR', Dexterity: 'DEX', Constitution: 'CON', Intelligence: 'INT', Wisdom: 'WIS', Charisma: 'CHA' }
const tidy = (s) => s.replace(/\s*\n\s*/g, ' ').replace(/\s+/g, ' ').trim()
const capitalize = (s) => s.charAt(0).toUpperCase() + s.slice(1)

function castingTime(raw) {
  const kind = raw.split(',')[0].trim()
  if (kind === 'Action' || kind.startsWith('Action (')) return 'action' // Plant Growth: "Action (Overgrowth) or 8 hours"
  if (kind === 'Bonus Action') return 'bonus'
  if (kind === 'Reaction') return 'reaction'
  return 'other' // 1 minute, 10 minutes, 1 hour...
}

// Some ranges in the source have the components stuck on: "Self Component: V".
const range = (raw) => raw.replace(/\s*Component:.*$/, '').replace(/(\d+) feet\b/, '$1 ft').trim()

function duration(raw, concentration) {
  // The concentration flag covers "Concentration", so drop it and "up to" from the text.
  const text = concentration ? raw.replace(/^(concentration,?\s*)?up to\s+/i, '') : raw
  return capitalize(text.trim())
}

/** A short line of facts for the action card: "8d6 Fire · DEX save". Empty if there's nothing to pull out. */
function facts(s) {
  const parts = []
  const trigger = s.casting_time.match(/, which you take (.*)$/)
  if (trigger) parts.push(`Cast ${trigger[1]}`)
  if (castingTime(s.casting_time) === 'other') parts.push(`Casting time: ${s.casting_time}`)

  const dmg = s.damage?.damage_at_slot_level?.[String(s.level)] ?? s.damage?.damage_at_character_level?.['1']
  if (dmg) parts.push(`${dmg} ${s.damage.damage_type?.name ?? ''}`.trim())
  const heal = s.description.match(/regains? (?:a number of )?Hit Points equal to (\d+d\d+)( plus your spellcasting ability modifier)?/)
  if (heal) parts.push(`Heals ${heal[1]}${heal[2] ? ' + mod' : ''}`)

  if (s.attack_type) parts.push(`${capitalize(s.attack_type)} spell attack`)
  else {
    const save = s.description.match(/(Strength|Dexterity|Constitution|Intelligence|Wisdom|Charisma) saving throw/)
    if (save) parts.push(`${ABILITY[save[1]]} save`)
  }
  if (s.level === 0 && dmg && /Cantrip Upgrade/i.test(s.description)) parts.push('more damage at levels 5, 11, 17')
  return parts.join(' · ')
}

function convert(s) {
  const concentration = s.concentration || /concentration/i.test(s.duration)
  const description = tidy(s.description)
  const upcast = s.level > 0 && (!!s.higher_level || /higher[- ]level spell slot/i.test(s.description))
  const summary = facts(s)
  return {
    srdId: s.index,
    name: s.name,
    level: s.level,
    castingTime: castingTime(s.casting_time),
    concentration,
    ritual: !!s.ritual,
    upcast,
    range: range(s.range),
    duration: duration(s.duration, concentration),
    // Spells with nothing to pull out (Bless, Haste) get the SRD text as the note. The rest get the
    // short facts as the note, and the SRD text to expand on the card.
    note: summary || description,
    ...(summary ? { description } : {}),
    classes: s.classes.map((c) => c.name),
    school: s.school.name,
  }
}

const all = JSON.parse(readFileSync(input, 'utf8'))
const spells = all
  .filter((s) => s.level <= MAX_LEVEL)
  .map(convert)
  .sort((a, b) => a.level - b.level || a.name.localeCompare(b.name))

const out = `// GENERATED by scripts/build-srd-spells.mjs. Don't edit by hand; fix the script and run it again.
//
// This work includes material from the System Reference Document 5.2 ("SRD 5.2") by Wizards of
// the Coast LLC, available at https://www.dndbeyond.com/srd. The SRD 5.2 is licensed under the
// Creative Commons Attribution 4.0 International License, available at
// https://creativecommons.org/licenses/by/4.0/legalcode.
//
// Spell data via the 5e-bits 5e-database project (https://github.com/5e-bits/5e-database, MIT).
// Cantrips to level ${MAX_LEVEL} only. Notes are short facts pulled from the SRD text; the full text is in "description".

import type { SrdSpell } from '../rules/types'

export const SRD_SPELLS: SrdSpell[] = [
${spells.map((s) => `  ${JSON.stringify(s)},`).join('\n')}
]
`
const target = fileURLToPath(new URL('../src/data/srdSpells.ts', import.meta.url))
writeFileSync(target, out)
const byLevel = spells.reduce((m, s) => ({ ...m, [s.level]: (m[s.level] ?? 0) + 1 }), {})
console.log(`Wrote ${spells.length} spells to src/data/srdSpells.ts`, byLevel)
